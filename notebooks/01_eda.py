# Function to plot scatterplots for 2 variables by a categorical feature
def facet_scatter(feature1, feature2, facet_feature):
  """
  Plots scatterplots for 2 variables by a categorical feature
  """
  fig = px.scatter(
      df,
      x=feature1,
      y=feature2,
      color="Churn",
      facet_col=facet_feature,
      opacity=0.6,
      hover_data=df.columns,
      title=f"{feature1} vs {feature2} by {facet_feature}"
  )
  fig.update_traces(marker=dict(size=5))
  fig.show()

