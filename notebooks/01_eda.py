def churned_distribution(feature):
  # Filter only churned customers
  churned = df[df['Churn'] == 'Yes']

  # Count churned customers by feature
  churn_by_feature = churned[feature].value_counts()

  # Pie chart
  fig = px.pie(
      names=churn_by_feature.index,
      values=churn_by_feature.values,
      title=f'Churn Distribution by {feature} (Only Churned Customers)',
      hole=0.3  # optional: makes it a donut chart
  )

  fig.update_traces(textposition='inside', textinfo='percent+label')
  fig.show()

