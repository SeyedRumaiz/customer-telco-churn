def scatter(feature1, feature2):
  """
  Plots a scatterplot between 2 numerical features
  """
  fig = px.scatter(
      df,
      x=feature1,
      y=feature2,
      color='Churn',
      opacity=0.6,
      hover_data=df.columns,
      trendline='ols',
      title=f"{feature1} vs {feature2} by Churn"
  )
  fig.show()

